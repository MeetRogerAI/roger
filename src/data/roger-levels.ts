export type VerificationCode = keyof typeof VERIFICATION_CODES;

/** The codes an item's printed code is made of (`ZI + S` → ZI, S). */
export function codeParts(code: string): VerificationCode[] {
  return code.split("+").map((c) => c.trim()) as VerificationCode[];
}

