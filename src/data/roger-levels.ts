/** The rules (levels file section 2), as data. Every number a ruling can change is here. */
export const LEVEL_RULES = {
  /** Rule 2.2: the current Zack run and the previous three, per platform. */
  windowRuns: 4,
  /** A submission older than this drops out of the window, so a platform that stopped running shows no stale 1s. */
  windowMaxAgeWeeks: 8,
  /**
   * Rule 2.2's cadence rule: a routine whose `last_run` is at most this many
   * days before the submission counts as running. Rule 2.2 says only "inside
   * its cadence"; the figures are the B4 plan's (Built as recommended 10 and 26):
   * daily 2 days, weekly 9 days and monthly 5 weeks, with the rest B4's
   * reading (weekdays spans a weekend; `other` is the 7 days Zack sees).
   * Pending Peter's sign-off (S23).
   */
  cadenceGraceDays: { hourly: 2, several_daily: 2, daily: 2, weekdays: 4, weekly: 9, monthly: 35, other: 7 },
  fastCadences: FAST_CADENCES,
  slowCadences: SLOW_CADENCES,
  /** Rule 2.3: 70% of a level's standard electives, rounded up. */
  electiveShare: 0.7,
  /** Fallback answers fill at most this share of a level's needed electives, rounded down. S items aren't capped. */
  maxFallbackElectiveShare: 0.5,
  /** Rule 2.1: at least this many core items of a level live from Zack or Roger evidence. */
  minVerifiedCore: 3,
  /** Rule 2.1, R28: a guardrail item's self-report answer expires after one Season. */
  guardrailSelfReportMaxWeeks: 26,
  /** R32: a verified newcomer at these levels gets the review hold. */
  reviewHoldLevels: [7, 8],
  reviewHoldAlertsPerDay: 5,
  /** Rule 2.6, R28: an item is 1 if any platform's window shows it. */
  platformsCombine: true,
} as const;
export type LevelRules = typeof LEVEL_RULES;

/** Electives needed for a level with this many standard electives: 70%, rounded up (5 of 6, 10 of 14). */
export function electivesNeeded(standardElectives: number, rules: Pick<LevelRules, "electiveShare"> = LEVEL_RULES): number {
  return Math.ceil((standardElectives * Math.round(rules.electiveShare * 100)) / 100);
}

/** How many of the needed electives fallback answers may fill (rounded down). */
export function fallbackElectivesAllowed(needed: number, rules: Pick<LevelRules, "maxFallbackElectiveShare"> = LEVEL_RULES): number {
  return Math.floor((needed * Math.round(rules.maxFallbackElectiveShare * 100)) / 100);
}

