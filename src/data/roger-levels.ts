/** A short, stable hash (53 bits as hex) of a string; no imports, so the file stays usable in the browser. */
function hash53(s: string): string {
  let h1 = 0xdeadbeef;
  let h2 = 0x41c6ce57;
  for (let i = 0; i < s.length; i++) {
    const c = s.charCodeAt(i);
    h1 = Math.imul(h1 ^ c, 2654435761);
    h2 = Math.imul(h2 ^ c, 1597334677);
  }
  h1 = Math.imul(h1 ^ (h1 >>> 16), 2246822507) ^ Math.imul(h2 ^ (h2 >>> 13), 3266489909);
  h2 = Math.imul(h2 ^ (h2 >>> 16), 2246822507) ^ Math.imul(h1 ^ (h1 >>> 13), 3266489909);
  return (4294967296 * (2097151 & h2) + (h1 >>> 0)).toString(16).padStart(14, "0");
}

/**
 * The version of the items and rules a level was computed under. Only what
 * scoring reads is hashed: wording (`statement`, `short`, `settledBy`,
 * `ruling`) is left out, so a wording edit doesn't rescore everyone.
 */
export function levelsRulesVersion(items: readonly LevelItem[], rules: unknown): string {
  const scored = items.map((i) => ({
    id: i.id,
    level: i.level,
    kind: i.kind,
    code: i.code,
    guardrail: i.guardrail,
    status: i.status,
    source: i.source,
    check: i.check,
    partsAcrossWindow: i.partsAcrossWindow ?? false,
    horizonWeeks: i.horizonWeeks ?? null,
    thresholds: i.thresholds ?? null,
  }));
  return hash53(JSON.stringify({ items: scored, rules }));
}

