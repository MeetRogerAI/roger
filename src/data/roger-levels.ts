export type LevelItemKind = "core" | "elective" | "design";
/**
 * How contract v1 settles the item: `full` (its fields settle it), `proxy`
 * (they settle a stated approximation), `fallback` (no field can, so Zack's
 * self-report answer settles it and counts as self-reported), `self`
 * (self-reported by design).
 */
export type LevelItemStatus = "full" | "proxy" | "fallback" | "self";
/** Where a live 1 comes from, for rule 2.1's three verified core items. */
export type LevelItemSource = "zack" | "roger" | "self";

export type LevelItem = {
  /** `N.xx`, where N is the level the item unlocks; `N.Dx` for design craft. */
  id: string;
  level: number;
  /** C, E or D in the chart. Design craft electives count when met, never against. */
  kind: LevelItemKind;
  /** The verification code as printed (`ZI`, `ZI + S`, …). */
  code: string;
  /** The statement starts "Guardrail:". */
  guardrail: boolean;
  /** Word for word from the chart. */
  statement: string;
  /** A plain label for reason lines and admin gap lists, where the statement is too long. Pending wording sign-off. */
  short: string;
  status: LevelItemStatus;
  /** For mixed codes: the Zack (or Roger) part when it is required, so a live 1 is verified. */
  source: LevelItemSource;
  /** The contract fields and Roger facts that settle it. Admin-facing, never shown to members. */
  settledBy: string;
  check: LevelCheck;
  /** A mixed-code item whose top-level `all_of` parts may each be met by a different submission in the window. */
  partsAcrossWindow?: true;
  /** The item names a period: look back this many weeks across all submissions, not the 4-run window. */
  horizonWeeks?: number;
  /** A threshold recorded as data, even where contract v1 can't enforce it (see `settledBy`). */
  thresholds?: Readonly<Record<string, number | boolean>>;
  /** Set when a threshold or kind is an S23 recommendation, not yet Peter's ruling. */
  ruling?: string;
};

